#!/usr/bin/env python3
from __future__ import annotations
import argparse, pathlib, re, sys
from fractions import Fraction as F

HERE = pathlib.Path(__file__).resolve()
THESIS = HERE.parents[1]
ROOT = THESIS.parent
OUT = THESIS / "generated" / "canonical.tex"


def read(path):
    return (ROOT / path).read_text(encoding="utf-8")


def parse_int(pattern, text, name):
    m = re.search(pattern, text)
    if not m:
        raise SystemExit(f"cannot extract {name}")
    return int(m.group(1).replace(",", ""))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    tc = read("evidence/transport_circle_certificate.txt")
    ch = read("evidence/chiral_law_certificate.txt")
    tc_count = parse_int(r"over\s+(\d+)\s+rational", tc, "transport count")
    local = parse_int(r"local_states=(\d+)", ch, "local states")
    global_states = parse_int(r"global_states=(\d+)", ch, "global states")

    # Recompute the declared finite domains from their source definitions.
    transport_expected = len(range(1,12))*len(range(65))*5
    if tc_count != transport_expected:
        raise SystemExit(f"transport count mismatch: cert={tc_count}, code-domain={transport_expected}")
    if local != 64 or global_states != 2**24:
        raise SystemExit("chiral certificate state counts disagree with defined state spaces")

    # Recompute CRTC exact grid sizes from the declared domains in the test source.
    crtctest = read("research/crtc/tests/test_exhaustive_exact_grid.py")
    boltz_points = len(range(1,96))*len(range(101))
    counter_points = len(range(-500,501))
    counter_off = counter_points - 1
    if boltz_points != 9595 or counter_points != 1001 or counter_off != 1000:
        raise SystemExit("internal finite-grid arithmetic failure")
    # Guard against silent source-domain changes.
    compact = re.sub(r"\s+", "", crtctest)
    for token in ["range(1,96)","range(101)","range(-500,501)","self.assertEqual(count,9595)","self.assertEqual((count,nonzero),(1001,1000))"]:
        if token not in compact:
            raise SystemExit(f"CRTC test domain changed; missing {token}")

    # Count current unit tests structurally. unittest discovers one method per test_ definition.
    tests = 0
    for p in sorted((ROOT / "research/crtc/tests").glob("test_*.py")):
        txt = p.read_text(encoding="utf-8")
        tests += len(re.findall(r"^\s+def\s+test_[A-Za-z0-9_]+\s*\(", txt, re.M))
    if tests != 35:
        raise SystemExit(f"CRTC unit-test count changed: {tests}, expected verified baseline 35")

    # Verify the exact endpoint entropy repair remains present in source.
    entropy = read("polyforms/entropy.hx")
    halts = 0
    for line in entropy.splitlines():
        if not line.startswith("CELL "):
            continue
        parts = line.split()
        if len(parts) != 10:
            continue
        coords = [int(v) for v in parts[1:6]]
        opcode = int(parts[6])
        if opcode == 0 and sum(1 for v in coords if abs(v) == 2) == 1 and sum(1 for v in coords if v != 0) == 1:
            halts += 1
    if halts != 10:
        raise SystemExit(f"entropy program exposes {halts} signed-axis HALT cells; expected exactly ten")

    # Verify critical formulas remain represented in executable source/tests.
    tctest = read("tests/test_transport_circle.py")
    for token in ["A = 1 / (2*D)", "den = 1 + F(4, 3)*d*d", "F(-1, 4)"]:
        if token not in tctest:
            raise SystemExit(f"transport source formula changed; missing {token}")

    body = rf"""% AUTO-GENERATED by thesis/tools/generate_fragments.py. Do not edit.
\newcommand{{\HXTransportGridPoints}}{{{tc_count:,}}}
\newcommand{{\HXLocalStates}}{{{local}}}
\newcommand{{\HXGlobalStates}}{{{global_states:,}}}
\newcommand{{\CRTCUnitTests}}{{{tests}}}
\newcommand{{\CRTCBoltzmannGridPoints}}{{{boltz_points:,}}}
\newcommand{{\CRTCCounterGridPoints}}{{{counter_points:,}}}
\newcommand{{\CRTCCounterOffCircle}}{{{counter_off:,}}}
\newcommand{{\ThesisVerificationDate}}{{27 September 2026}}
"""
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != body:
            raise SystemExit("generated/canonical.tex is stale")
        print("PASS: canonical thesis fragments match executable sources and certificates")
    else:
        OUT.write_text(body, encoding="utf-8")
        print(f"wrote {OUT}")

if __name__ == "__main__":
    main()
